pub const DEFAULT_PROGRAM: &str = r#"; Hello World
.ORIG x3000

LEA     R0, MESSAGE     ; R0 = address of the message
PUTS                    ; print the string at R0
HALT

MESSAGE .STRINGZ "Hello, World!"
        .END"#;

lazy_static::lazy_static! {
    /// Files picked in the (async, on the web) open dialog, waiting to be opened by the app.
    pub static ref OPENED_FILES: Mutex<Vec<Document>> = Mutex::new(Vec::new());
    /// Memory addresses generated by the lines selected in the editor (when the file is the
    /// loaded program), so the memory pane can highlight them.
    pub static ref SOURCE_SELECTION: Mutex<Vec<usize>> = Mutex::new(Vec::new());
    /// The register being hovered somewhere (CPU pane or an editor), written this frame...
    pub static ref REGISTER_HOVER_NEXT: Mutex<Option<usize>> = Mutex::new(None);
    /// ...and read the next frame, so panes drawn earlier in the frame still see it
    pub static ref REGISTER_HOVER: Mutex<Option<usize>> = Mutex::new(None);
    /// A memory address another pane asked the editor holding its source to show
    pub static ref REVEAL_ADDR: Mutex<Option<usize>> = Mutex::new(None);
}

/// Show the open file dialog. Picked files are queued in [`OPENED_FILES`].
pub fn open_file_dialog() {
    #[cfg(target_arch = "wasm32")]
    wasm_bindgen_futures::spawn_local(async move {
        if let Some(file) = rfd::AsyncFileDialog::new()
            .add_filter("Assembly", &["asm", "txt", "lc3"])
            .pick_file()
            .await
        {
            let bytes = file.read().await;
            if let Ok(content) = String::from_utf8(bytes) {
                if let Ok(mut q) = OPENED_FILES.lock() {
                    q.push(Document::new(file.file_name(), content));
                }
            }
        }
    });

    #[cfg(not(target_arch = "wasm32"))]
    if let Some(path) = rfd::FileDialog::new()
        .add_filter("Assembly", &["asm", "txt", "lc3"])
        .pick_file()
    {
        if let Ok(content) = std::fs::read_to_string(&path) {
            let name = path
                .file_name()
                .unwrap_or_default()
                .to_string_lossy()
                .into_owned();
            let mut doc = Document::new(name, content);
            doc.path = Some(path.to_string_lossy().into_owned());
            if let Ok(mut q) = OPENED_FILES.lock() {
                q.push(doc);
            }
        }
    }
}

/// One open source file.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Document {
    pub id: u64,
    pub name: String,
    pub text: String,
    /// The text as of the last save/load, used to show the modified dot
    #[serde(default)]
    pub saved_text: String,
    /// Path on disk (native only)
    #[serde(default)]
    pub path: Option<String>,
    /// 0-based lines with a breakpoint
    #[serde(default)]
    pub breakpoints: BTreeSet<usize>,
    /// The text as it was when this document was last assembled and loaded
    #[serde(skip)]
    pub assembled_text: Option<String>,
    #[serde(skip)]
    diagnostics: Vec<Diagnostic>,
    #[serde(skip)]
    diagnosed_text: Option<String>,
    /// Hash of the text and the time it last changed, to wait for a pause in typing
    #[serde(skip)]
    edit_stamp: (u64, f64),
}

impl Document {
    pub fn new(name: impl Into<String>, text: impl Into<String>) -> Self {
        let text = text.into();
        let id = {
            let mut n = crate::panes::NEXT_ID.lock();
            *n += 1;
            *n + 1_000_000
        };
        Self {
            id,
            name: name.into(),
            saved_text: text.clone(),
            text,
            path: None,
            breakpoints: BTreeSet::new(),
            assembled_text: None,
            diagnostics: Vec::new(),
            diagnosed_text: None,
            edit_stamp: (0, 0.0),
        }
    }

    pub fn is_modified(&self) -> bool {
        self.text != self.saved_text
    }

    /// Is the emulator running exactly the code shown in this document?
    pub fn is_loaded(&self) -> bool {
        self.assembled_text.as_deref() == Some(self.text.as_str())
    }

    /// The program this document loaded into the emulator, if it is still loaded unchanged.
    pub fn loaded_program<'a>(&self, emulator: &'a Emulator) -> Option<&'a LoadedProgram> {
        if !self.is_loaded() {
            return None;
        }
        emulator
            .loaded_programs
            .iter()
            .find(|p| p.source_id == self.id)
    }

    /// Re-assemble in the background to find errors, once typing has paused for a moment.
    fn refresh_diagnostics(&mut self, ctx: &egui::Context) {
        if self.diagnosed_text.as_deref() == Some(self.text.as_str()) {
            return;
        }
        let now = ctx.input(|i| i.time);
        let hash = {
            use std::hash::{Hash, Hasher};
            let mut h = std::collections::hash_map::DefaultHasher::new();
            self.text.hash(&mut h);
            h.finish()
        };
        if hash != self.edit_stamp.0 {
            let first = self.diagnosed_text.is_none();
            self.edit_stamp = (hash, if first { now - 1.0 } else { now });
        }
        const PAUSE: f64 = 0.7;
        if now - self.edit_stamp.1 < PAUSE {
            ctx.request_repaint_after(std::time::Duration::from_secs_f64(
                PAUSE - (now - self.edit_stamp.1) + 0.02,
            ));
            return;
        }
        self.diagnostics = match Emulator::parse_program(&self.text, None) {
            Ok(_) => Vec::new(),
            Err(e) => vec![diagnostic_from_error(&e)],
        };
        self.diagnosed_text = Some(self.text.clone());
    }

    pub fn diagnostics(&self) -> &[Diagnostic] {
        &self.diagnostics
    }
}

/// Mark a register as hovered this frame.
pub fn hover_register(r: usize) {
    if let Ok(mut h) = REGISTER_HOVER_NEXT.lock() {
        *h = Some(r);
    }
}

/// Called once per frame by the app: publish last frame's hovered register.
pub fn swap_register_hover(ctx: &egui::Context) {
    let next = REGISTER_HOVER_NEXT.lock().ok().and_then(|mut h| h.take());
    if let Ok(mut cur) = REGISTER_HOVER.lock() {
        if *cur != next {
            ctx.request_repaint();
        }
        *cur = next;
    }
}

pub fn diagnostic_from_error(e: &ParseError) -> Diagnostic {
    match e {
        ParseError::TokenizeError(msg, line) => Diagnostic {
            line: line.saturating_sub(1),
            message: msg.clone(),
        },
        ParseError::GenerationError(msg, span) => Diagnostic {
            line: span.line.saturating_sub(1),
            message: msg.clone(),
        },
    }
}

